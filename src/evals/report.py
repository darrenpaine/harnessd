"""Baselines, the regression gate and REPORT.md (SPEC-0011 B-0004, B-0005)."""

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from evals.records import RunRecord, model_key

MAX_VALUE = 80  # characters of an expected or actual value shown in the report


class BaselineRefusedError(Exception):
    """The run can't be a baseline because a must_pass case failed (B-0004)."""

    def __init__(self, run_id: str, failures: Sequence[str]) -> None:
        super().__init__(
            f"{run_id} has must_pass failures: {', '.join(failures)}; not accepted"
        )


class Baseline(BaseModel):
    """The full run accepted as a model's baseline."""

    run_id: str
    score: float


def load_runs(directory: Path) -> list[RunRecord]:
    """Every run file in `directory`, oldest first."""
    runs = [
        RunRecord.model_validate_json(path.read_text(encoding="utf-8"))
        for path in directory.glob("*.json")
    ]
    return sorted(runs, key=lambda r: (r.started_at, r.run_id))


def load_baselines(directory: Path) -> dict[str, Baseline]:
    """Baselines by model key (`<provider>__<model>`)."""
    return {
        path.stem: Baseline.model_validate_json(path.read_text(encoding="utf-8"))
        for path in sorted(directory.glob("*.json"))
    }


def accept_baseline(
    runs: Sequence[RunRecord], provider: str, model: str, directory: Path
) -> Baseline | None:
    """Write the model's latest full run as its baseline; None if it has none.
    Raises BaselineRefusedError if that run has a must_pass failure (B-0004)."""
    key = model_key(provider, model)
    full = [r for r in runs if not r.partial and model_key(r.provider, r.model) == key]
    if not full:
        return None
    latest = full[-1]
    if latest.totals.must_pass_failures:
        raise BaselineRefusedError(latest.run_id, latest.totals.must_pass_failures)
    baseline = Baseline(run_id=latest.run_id, score=latest.totals.score)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"{key}.json").write_text(
        baseline.model_dump_json(indent=2) + "\n", encoding="utf-8"
    )
    return baseline


def gate(record: RunRecord, baseline: Baseline | None, points: float) -> list[str]:
    """Why a full run fails (B-0004): any must_pass failure, or a score more
    than `points` below the baseline. Partial runs are never gated."""
    if record.partial:
        return []
    reasons = [f"must_pass case failed: {i}" for i in record.totals.must_pass_failures]
    if baseline is not None:
        drop = round((baseline.score - record.totals.score) * 100, 6)
        if drop > points:
            reasons.append(
                f"score {record.totals.score:.3f} is {drop:g} points below "
                f"baseline {baseline.score:.3f} (limit {points:g})"
            )
    return reasons


def render_report(runs: Sequence[RunRecord], baselines: dict[str, Baseline]) -> str:
    """REPORT.md from the run files and baselines. Per model: the latest full
    score against the baseline, the run history (newest first) and the
    latest run's failing cases. The same inputs always give the same text."""
    lines = [
        "# Eval report",
        "",
        "Generated by `make evals` from `evals/runs/` and `evals/baselines/` "
        "(SPEC-0011). Do not edit.",
    ]
    by_model: dict[str, list[RunRecord]] = {}
    for run in runs:
        by_model.setdefault(model_key(run.provider, run.model), []).append(run)
    if not by_model:
        lines += ["", "No runs yet."]
    for key in sorted(by_model):
        lines += _model_section(by_model[key], baselines.get(key))
    return "\n".join(lines) + "\n"


def write_report(root: Path) -> Path:
    """Regenerate `root/REPORT.md` from `root/runs` and `root/baselines`."""
    path = root / "REPORT.md"
    path.write_text(report_for(root), encoding="utf-8")
    return path


def report_for(root: Path) -> str:
    return render_report(load_runs(root / "runs"), load_baselines(root / "baselines"))


def _model_section(runs: list[RunRecord], baseline: Baseline | None) -> list[str]:
    latest = runs[-1]
    full = [r for r in runs if not r.partial]
    lines = ["", f"## {latest.provider} {latest.model}", ""]
    score = f"{full[-1].totals.score:.3f}" if full else "no full run"
    if baseline is None:
        lines.append(f"Latest full score: {score}; no baseline.")
    else:
        lines.append(
            f"Latest full score: {score}; baseline {baseline.score:.3f} "
            f"(`{baseline.run_id}`)."
        )
    lines += [
        "",
        "### History",
        "",
        "| Run | Commit | Kind | Cases | Repeats | Score | Must-pass failures "
        "| p50 ms | p95 ms | Tokens |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for run in reversed(runs):
        totals = run.totals
        commit = run.git_sha[:7] + (" (dirty)" if run.dirty else "")
        cells = [
            f"`{run.run_id}`",
            commit,
            "partial" if run.partial else "full",
            str(len(run.cases)),
            str(run.repeats),
            f"{totals.score:.3f}",
            ", ".join(totals.must_pass_failures) or "-",
            str(totals.latency_p50_ms),
            str(totals.latency_p95_ms),
            str(totals.tokens) if totals.tokens is not None else "-",
        ]
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    lines += ["", f"### Failing cases in `{latest.run_id}`", ""]
    failing = [c for c in latest.cases if not c.passed]
    if not failing:
        lines.append("None.")
    for result in failing:
        must = ", must_pass" if result.must_pass else ""
        lines.append(f"- **{result.id}** (score {result.score:.2f}{must})")
        for f in result.failures:
            lines.append(
                f"  - repeat {f.repeat}, turn {f.turn}, `{f.check}`: expected "
                f"{_value(f.expected)}, got {_value(f.actual)}"
            )
    return lines


def _value(value: Any) -> str:
    text = json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)
    if len(text) > MAX_VALUE:
        text = text[: MAX_VALUE - 1] + "…"
    return "`" + text.replace("`", "'").replace("\n", " ") + "`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")
